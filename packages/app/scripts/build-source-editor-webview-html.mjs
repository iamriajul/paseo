import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDirectory, "..");
const repoRoot = path.resolve(appRoot, "../..");
const editorDirectory = path.join(appRoot, "src/file-panels/source/editor/native");
const entry = path.join(editorDirectory, "webview-entry.ts");
const output = path.join(editorDirectory, "webview-html.ts");
const checkOnly = process.argv.includes("--check");

async function resolveTsPath(basePath) {
  for (const candidate of [basePath, `${basePath}.ts`, `${basePath}.tsx`, `${basePath}.js`]) {
    try {
      if ((await fs.stat(candidate)).isFile()) return candidate;
    } catch {
      // Try the next candidate.
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "paseo-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTsPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
  },
};

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["ios15", "chrome100"],
  minify: true,
  legalComments: "none",
  plugins: [aliasPlugin],
  logLevel: "warning",
});

const javascript = result.outputFiles[0]?.text;
if (!javascript) throw new Error("source editor WebView bundle produced no JavaScript");

// The page runs only this bundle: no network, no frames, no navigation (the host refuses it too).
const csp = [
  "default-src 'none'",
  "script-src 'unsafe-inline'",
  "style-src 'unsafe-inline'",
  "img-src data:",
  "font-src data:",
  "form-action 'none'",
  "base-uri 'none'",
].join("; ");
const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta http-equiv="Content-Security-Policy" content="${csp}" />
    <meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover, interactive-widget=resizes-content" />
    <style>
      html, body, #source-editor-host { width: 100%; height: 100%; margin: 0; padding: 0; overflow: hidden; }
      html, body { overscroll-behavior: none; -webkit-text-size-adjust: 100%; }
      #source-editor-host { display: flex; min-width: 0; min-height: 0; }
      #source-editor-host > .cm-editor { flex: 1; min-width: 0; }
      * { -webkit-tap-highlight-color: transparent; }
    </style>
  </head>
  <body>
    <script>${javascript.replace(/<\/script/gi, "<\\/script")}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/scripts/build-source-editor-webview-html.mjs. Do not edit by hand.
export const sourceEditorWebViewHtml =
  ${JSON.stringify(html)};
`;

const relativeOutput = path.relative(repoRoot, output);
if (checkOnly) {
  const existing = await fs.readFile(output, "utf8").catch(() => null);
  if (existing !== contents) {
    console.error(
      `${relativeOutput} is stale. Run npm --prefix packages/app run build:source-editor-webview.`,
    );
    process.exit(1);
  }
  console.log(`${relativeOutput} is current (${html.length} bytes)`);
} else {
  await fs.writeFile(output, contents);
  console.log(`Wrote ${relativeOutput} (${html.length} bytes)`);
}
