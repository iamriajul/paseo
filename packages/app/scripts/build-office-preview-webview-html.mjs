import esbuild from "esbuild";
import { spawnSync } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(appRoot, "../..");
const documents = [
  ["docx", "office-preview-webview-docx-entry.ts", "officePreviewDocxWebViewHtml"],
  ["xlsx", "office-preview-webview-xlsx-entry.ts", "officePreviewXlsxWebViewHtml"],
  ["pptx", "office-preview-webview-pptx-entry.ts", "officePreviewPptxWebViewHtml"],
];

async function resolveTsPath(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    `${basePath}.js`,
    `${basePath}.jsx`,
    path.join(basePath, "index.ts"),
    path.join(basePath, "index.tsx"),
    path.join(basePath, "index.js"),
    path.join(basePath, "index.jsx"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isFile()) return candidate;
    } catch {
      // try next candidate
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "paseo-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTsPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
    build.onResolve({ filter: /^stream$/ }, () => ({
      path: path.join(appRoot, "src/components/office-preview-stream-shim.ts"),
    }));
    build.onResolve({ filter: /^events$/ }, () => ({
      path: path.join(repoRoot, "node_modules/events/events.js"),
    }));
    build.onResolve({ filter: /^buffer$/ }, () => ({
      path: path.join(repoRoot, "node_modules/buffer/index.js"),
    }));
    build.onResolve({ filter: /^util$/ }, () => ({
      path: path.join(repoRoot, "node_modules/util/util.js"),
    }));
  },
};

const outputs = [];

for (const [kind, entryName, exportName] of documents) {
  const result = await esbuild.build({
    entryPoints: [path.join(appRoot, "src/components", entryName)],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["ios15", "chrome100"],
    minify: true,
    legalComments: "none",
    loader: {
      ".css": "text",
    },
    plugins: [aliasPlugin],
    logLevel: "info",
  });

  const js = result.outputFiles[0]?.text;
  if (!js) {
    throw new Error(`office preview ${kind} webview bundle produced no JavaScript`);
  }

  const safeJs = js.replace(/<\/script/gi, "<\\/script");
  // Excel reloads the workbook with an XHR to a blob: URL of the bytes already
  // in the page, and both Excel and Word call new Function. connect-src allows
  // that blob URL and no origin. Remote fetch, images, frames, and form posts
  // stay refused, same as the HTML preview.
  const csp = [
    "default-src 'none'",
    "script-src 'unsafe-inline' 'unsafe-eval' blob:",
    "style-src 'unsafe-inline'",
    "img-src data: blob:",
    "font-src data: blob:",
    "media-src data: blob:",
    "connect-src blob:",
    "form-action 'none'",
    "base-uri 'none'",
    "frame-src 'none'",
    "object-src 'none'",
  ].join("; ");
  const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta http-equiv="Content-Security-Policy" content="${csp}" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"
    />
  </head>
  <body>
    <div id="host"></div>
    <script>${safeJs}</script>
  </body>
</html>`;

  const output = path.join(appRoot, "src/components", `office-preview-webview-${kind}-html.ts`);
  const contents = `// Generated by packages/app/scripts/build-office-preview-webview-html.mjs.
// Do not edit by hand.

export const ${exportName} = ${JSON.stringify(html)};
`;
  await fs.writeFile(output, contents);
  outputs.push(output);
  console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
}

const format = spawnSync(path.join(repoRoot, "node_modules/.bin/oxfmt"), outputs, {
  stdio: "inherit",
});
if (format.status !== 0) {
  throw new Error("office preview webview format failed");
}
