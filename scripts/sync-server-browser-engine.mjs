#!/usr/bin/env node
// The server browser runs the desktop browser-automation engine against a daemon-owned Chromium.
// The server cannot import desktop (desktop depends on server), so the engine is vendored.
// Run this after an upstream change to the desktop engine; the drift test fails until you do.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const ENGINE_SOURCE_DIR = join(root, "packages/desktop/src/features/browser-automation");
export const ENGINE_TARGET_DIR = join(root, "packages/server/src/server/server-browser/engine");
export const ENGINE_FILES = [
  "actionability.ts",
  "aria-snapshot-script.ts",
  "cdp-session-queue.ts",
  "service.ts",
  "snapshot-engine.ts",
  "trusted-input.ts",
];

const HEADER =
  "// GENERATED by scripts/sync-server-browser-engine.mjs from packages/desktop/src/features/browser-automation.\n" +
  "// Do not edit; change the desktop original and rerun the script.\n";

export function transformEngineSource(source) {
  // The only Electron dependency is a type; the server provides a structural copy.
  return (
    HEADER +
    source.replace(
      'import type { KeyboardInputEvent } from "electron";',
      'import type { KeyboardInputEvent } from "../electron-keyboard-event.js";',
    )
  );
}

export function expectedEngineFiles() {
  return ENGINE_FILES.map((name) => ({
    name,
    content: transformEngineSource(readFileSync(join(ENGINE_SOURCE_DIR, name), "utf8")),
  }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const { name, content } of expectedEngineFiles()) {
    writeFileSync(join(ENGINE_TARGET_DIR, name), content);
    console.log(`synced ${name}`);
  }
}
